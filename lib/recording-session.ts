import { AudioProcessor } from './audio-processor';

/** A generation changes before cancellation, so queued callbacks cannot commit. */
export class RecordingSession<T> {
  private generation = 0;
  private active: { id: number; snapshot: T } | null = null;

  begin(snapshot: T): number {
    const id = ++this.generation;
    this.active = { id, snapshot };
    return id;
  }

  isCurrent(id: number): boolean {
    return this.active?.id === id;
  }

  cancel(): T | null {
    const snapshot = this.active?.snapshot ?? null;
    this.active = null;
    ++this.generation;
    return snapshot;
  }

  finish(id: number): void {
    if (this.isCurrent(id)) this.active = null;
  }
}

export function appendTranscript(previous: string, next: string): string {
  const suffix = next.trim();
  if (!suffix) return previous;
  return previous ? `${previous}\n${suffix}` : suffix;
}

/** Merge WAVs generated by AudioProcessor; never concatenate their RIFF headers. */
export function mergeRecordingWavs(parts: Uint8Array[]): Uint8Array {
  const samples = parts.map(part => {
    const view = new DataView(part.buffer, part.byteOffset, part.byteLength);
    if (part.length < 44 || view.getUint32(0, false) !== 0x52494646 ||
        view.getUint32(8, false) !== 0x57415645 || view.getUint32(36, false) !== 0x64617461 ||
        view.getUint16(20, true) !== 1 || view.getUint16(22, true) !== 1 ||
        view.getUint32(24, true) !== 16000 || view.getUint16(34, true) !== 16 ||
        view.getUint32(40, true) !== part.length - 44 || (part.length - 44) % 2) {
      throw new Error('Expected a 16 kHz mono 16-bit PCM WAV recording');
    }
    return part.subarray(44);
  });
  const pcm = new Int16Array(samples.reduce((size, part) => size + part.length / 2, 0));
  let offset = 0;
  for (const part of samples) {
    const view = new DataView(part.buffer, part.byteOffset, part.byteLength);
    for (let i = 0; i < part.length; i += 2) pcm[offset++] = view.getInt16(i, true);
  }
  return new AudioProcessor(16000).createWavFile(pcm);
}

export function wavDuration(wav: Uint8Array): number {
  return (wav.length - 44) / (16000 * 2);
}
